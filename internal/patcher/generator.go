// Package patcher generates Kubernetes strategic merge patch manifests
// based on finops rightsizing recommendations.
package patcher

import (
	"fmt"
	"os"
	"strings"

	"github.com/dawidbera/kube-cost-lens/internal/finops"
	"github.com/dawidbera/kube-cost-lens/internal/k8s"
	"gopkg.in/yaml.v3"
)

// ResourceRequirements defines container CPU and memory requests and limits.
type ResourceRequirements struct {
	Requests map[string]string `yaml:"requests,omitempty"`
	Limits   map[string]string `yaml:"limits,omitempty"`
}

// ContainerPatch defines container-level patch elements.
type ContainerPatch struct {
	Name      string               `yaml:"name"`
	Resources ResourceRequirements `yaml:"resources"`
}

// PodSpecPatch defines pod spec level patch elements.
type PodSpecPatch struct {
	Containers []ContainerPatch `yaml:"containers"`
}

// PodTemplateSpecPatch defines template level patch elements.
type PodTemplateSpecPatch struct {
	Spec PodSpecPatch `yaml:"spec"`
}

// WorkloadSpecPatch defines controller spec level patch elements.
type WorkloadSpecPatch struct {
	Template PodTemplateSpecPatch `yaml:"template"`
}

// RootPatchManifest defines the root strategic merge patch structure.
type RootPatchManifest struct {
	Spec WorkloadSpecPatch `yaml:"spec"`
}

// GenerateStrategicMergePatch creates a formatted YAML manifest from a workload recommendation.
func GenerateStrategicMergePatch(rec finops.WorkloadRecommendation) (string, error) {
	var containerPatches []ContainerPatch

	for _, c := range rec.Containers {
		reqMap := make(map[string]string)
		limMap := make(map[string]string)

		reqMap["cpu"] = k8s.FormatCPU(c.RecommendedCPURequest)
		reqMap["memory"] = k8s.FormatMemoryBytes(c.RecommendedMemoryRequest)

		if c.RecommendedCPULimit > 0 {
			limMap["cpu"] = k8s.FormatCPU(c.RecommendedCPULimit)
		}
		if c.RecommendedMemoryLimit > 0 {
			limMap["memory"] = k8s.FormatMemoryBytes(c.RecommendedMemoryLimit)
		}

		containerPatches = append(containerPatches, ContainerPatch{
			Name: c.ContainerName,
			Resources: ResourceRequirements{
				Requests: reqMap,
				Limits:   limMap,
			},
		})
	}

	manifest := RootPatchManifest{
		Spec: WorkloadSpecPatch{
			Template: PodTemplateSpecPatch{
				Spec: PodSpecPatch{
					Containers: containerPatches,
				},
			},
		},
	}

	yamlData, err := yaml.Marshal(&manifest)
	if err != nil {
		return "", fmt.Errorf("failed to marshal YAML patch: %w", err)
	}

	header := fmt.Sprintf(
		"# Generated by kube-cost-lens for %s: %s/%s\n"+
			"# Estimated Monthly Savings: $%.2f (-%.1f%%)\n"+
			"# Apply with: kubectl patch %s %s -n %s --patch-file <this-file>\n",
		strings.ToLower(rec.WorkloadKind),
		rec.Namespace,
		rec.WorkloadName,
		rec.MonthlySavings,
		rec.SavingsPercentage,
		strings.ToLower(rec.WorkloadKind),
		rec.WorkloadName,
		rec.Namespace,
	)

	return header + string(yamlData), nil
}

// WritePatchToFile exports the YAML patch string to a specified file location.
func WritePatchToFile(filePath, content string) error {
	if err := os.WriteFile(filePath, []byte(content), 0600); err != nil {
		return fmt.Errorf("failed to write patch file to %q: %w", filePath, err)
	}
	return nil
}
