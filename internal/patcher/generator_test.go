package patcher

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/dawidbera/kube-cost-lens/internal/finops"
)

func TestGenerateStrategicMergePatch(t *testing.T) {
	rec := finops.WorkloadRecommendation{
		Namespace:    "default",
		WorkloadName: "payment-api",
		WorkloadKind: "Deployment",
		Replicas:     3,
		Containers: []finops.ContainerRecommendation{
			{
				ContainerName:            "payment-api",
				RecommendedCPURequest:    0.600,
				RecommendedCPULimit:      0.900,
				RecommendedMemoryRequest: 1536 * 1024 * 1024,
				RecommendedMemoryLimit:   2304 * 1024 * 1024,
			},
		},
		MonthlySavings:    118.20,
		SavingsPercentage: 83.1,
	}

	patchYAML, err := GenerateStrategicMergePatch(rec)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}

	if !strings.Contains(patchYAML, "# Generated by kube-cost-lens for deployment: default/payment-api") {
		t.Errorf("missing expected header in patch: %s", patchYAML)
	}
	if !strings.Contains(patchYAML, "payment-api") {
		t.Errorf("missing container name in patch: %s", patchYAML)
	}
	if !strings.Contains(patchYAML, "600m") {
		t.Errorf("missing 600m cpu request in patch: %s", patchYAML)
	}
	if !strings.Contains(patchYAML, "1536Mi") {
		t.Errorf("missing 1536Mi memory request in patch: %s", patchYAML)
	}
}

func TestWritePatchToFile(t *testing.T) {
	tmpDir := t.TempDir()
	filePath := filepath.Join(tmpDir, "patch.yaml")
	content := "test-content: true\n"

	if err := WritePatchToFile(filePath, content); err != nil {
		t.Fatalf("unexpected error writing patch: %v", err)
	}

	data, err := os.ReadFile(filePath)
	if err != nil {
		t.Fatalf("failed to read back written file: %v", err)
	}

	if string(data) != content {
		t.Errorf("expected %q, got %q", content, string(data))
	}
}
